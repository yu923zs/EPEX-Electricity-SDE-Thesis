# -*- coding: utf-8 -*-
"""
make_baseline_tables.py — 外部基准对比表（数字一律从逐种子结果文件重新聚合，禁止手抄）
Stage I: 本文方法(v13) vs 朴素SS-Normal(v2配置) vs ols1/ols3/lasso_cv/stepwise_bic
  来源: lab_rows_v13_T*_S*_light.csv, lab_rows_v2_T*_S*_none.csv, baselines_stage1.csv
Stage II: 本文方法(v13, 单尺度1h ECF) vs cmom(矩法κ1–6) vs cgmm(C-GMM κ1–8) vs mlefft(FFT密度MLE)
  来源: lab_rows_v13_T25000_S12_light.csv (or_/pl_ 列), baselines_stage2.csv
  指标: 6参数 bias/RMSE (T=25000, 12种子, 真值 R.DGP_LAB[dgp]["xi"])
输出: method_lab/results/table_stage1_baselines.csv (+ .tex)
      method_lab/results/table_stage2_baselines.csv (+ .tex)
"""
import os, sys, argparse
import numpy as np
import pandas as pd

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, HERE)
import run_lab as R

RES = R.RES_DIR
METS = ["tpr", "fdr", "f1", "wass", "medse"]

# (method_key, 中文标签, csv内方法名(None=同key), 来源文件列表)
STAGE1_SOURCES = [
    ("v13",      "本文方法", None,
     ["lab_rows_v13_T10000_S8_light.csv", "lab_rows_v13_T25000_S12_light.csv"]),
    ("ssnormal", "朴素 SS-Normal", None,
     ["lab_rows_v2_T10000_S8_none.csv", "lab_rows_v2_T25000_S12_none.csv"]),
    ("ols1",     "OLS-poly1", None, ["baselines_stage1.csv"]),
    ("ols3",     "OLS-poly3", None, ["baselines_stage1.csv"]),
    ("lasso_cv", "LASSO-CV", None, ["baselines_stage1.csv"]),
    ("stepwise", "逐步回归-BIC", "stepwise_bic", ["baselines_stage1.csv"]),
]
SHORT = {"v13": "v13", "ssnormal": "SS-N", "ols1": "ols1", "ols3": "ols3",
         "lasso_cv": "lasso", "stepwise": "step"}

# ---------------- Stage II ----------------
PNAMES = ["mu", "Cp", "Cm", "M", "G", "alpha"]
PLABS = [r"$\mu$", r"$C_{+}$", r"$C_{-}$", "$M$", "$G$", r"$\alpha$"]
# (method_key, 中文标签)
STAGE2_METHODS = [
    ("v13",    "本文 ECF"),
    ("cmom",   "C-Mom（矩法 $\\kappa_{1..6}$）"),
    ("cgmm",   "C-GMM（$\\kappa_{1..8}$）"),
    ("mlefft", "MLE-FFT"),
]
SRC_LABEL = {"oracle": "oracle", "plugin": "plugin"}


def load_stage2():
    """从逐种子结果文件重新聚合 bias/RMSE；并与 baselines_stage2_summary.csv 交叉核对。"""
    frames = []
    df = pd.read_csv(os.path.join(RES, "lab_rows_v13_T25000_S12_light.csv"))
    for src, pre in (("oracle", "or_"), ("plugin", "pl_")):
        rec = pd.DataFrame({"method": "v13", "src": src, "dgp": df["dgp"],
                            "seed": df["seed"]})
        for p in PNAMES:
            rec[p] = df[pre + p].values
        frames.append(rec)
    b = pd.read_csv(os.path.join(RES, "baselines_stage2.csv"))
    frames.append(b[["method", "src", "dgp", "seed"] + PNAMES])
    rows = pd.concat(frames, ignore_index=True)
    tv = {d: np.array(R.DGP_LAB[d]["xi"], float) for d in "ABC"}
    for i, p in enumerate(PNAMES):
        rows[f"e_{p}"] = rows.apply(lambda r: r[p] - tv[r["dgp"]][i], axis=1)
    lab = {k: v for k, v in STAGE2_METHODS}
    rows["label"] = rows["method"].map(lab)
    agg = (rows.groupby(["method", "label", "src", "dgp"])
               .agg(n=("seed", "count"),
                    **{f"b_{p}": (f"e_{p}", "mean") for p in PNAMES},
                    **{f"r_{p}": (f"e_{p}", lambda s: float(np.sqrt(np.mean(s ** 2))))
                       for p in PNAMES})
               .reset_index())
    order = {k: i for i, (k, _) in enumerate(STAGE2_METHODS)}
    agg["ord"] = agg["method"].map(order)
    agg["src_ord"] = (agg["src"] == "plugin").astype(int)
    agg = agg.sort_values(["ord", "src_ord", "dgp"]).drop(
        columns=["ord", "src_ord"]).reset_index(drop=True)
    for key, _ in STAGE2_METHODS:                # 完整性校验
        for src in ("oracle", "plugin"):
            for dgp in "ABC":
                hit = agg[(agg["method"] == key) & (agg["src"] == src)
                          & (agg["dgp"] == dgp)]
                assert len(hit) == 1 and hit["n"].iloc[0] == 12, \
                    f"缺失数据块: {key} {src} DGP={dgp}"
    chk = pd.read_csv(os.path.join(RES, "baselines_stage2_summary.csv"))
    for _, r in chk.iterrows():                  # 交叉核对 run_baselines 自带汇总
        mine = agg[(agg["method"] == r["method"]) & (agg["src"] == r["src"])
                   & (agg["dgp"] == r["dgp"])]
        assert len(mine) == 1, f"summary 块无法匹配: {r['method']}/{r['src']}/{r['dgp']}"
        m = mine.iloc[0]
        for p in PNAMES:
            assert np.isclose(m[f"b_{p}"], r[f"b_{p}"], atol=5.1e-4), \
                f"bias 不一致 {r['method']}/{r['src']}/{r['dgp']}/{p}"
            assert np.isclose(m[f"r_{p}"], r[f"r_{p}"], atol=5.1e-4), \
                f"rmse 不一致 {r['method']}/{r['src']}/{r['dgp']}/{p}"
    return rows, agg


def stage2_tex(agg, kind):
    """kind='r' 输出 RMSE 表; kind='b' 输出 bias 表。"""
    nd = {"mu": 2, "Cp": 2, "Cm": 2, "M": 3, "G": 3, "alpha": 3}
    title = "RMSE（越小越好）" if kind == "r" else "偏差 bias"
    lines = [
        "% Auto-generated by make_baseline_tables.py — 数字来自逐种子结果文件重新聚合",
        "\\begin{table}[htbp]", "\\centering", "\\small",
        "\\caption{Stage II 非对称 TS 参数估计" + title +
        "：本文 ECF 与外部基准对比（$T=25{,}000$，12 种子）}",
        "\\label{tab:stage2_" + ("rmse" if kind == "r" else "bias") + "}",
        "\\begin{tabular}{lll" + "c" * len(PNAMES) + "}",
        "\\toprule",
        "方法 & 残差 & DGP & " + " & ".join(PLABS) + " \\\\",
        "\\midrule",
    ]
    nm = len(STAGE2_METHODS)
    for mi, (key, label) in enumerate(STAGE2_METHODS):
        blk = agg[agg["method"] == key]
        first_m = True
        for src in ("oracle", "plugin"):
            sub = blk[blk["src"] == src]
            first_s = True
            for _, r in sub.iterrows():
                cells = [label if first_m else "",
                         SRC_LABEL[src] if first_s else "", r["dgp"]]
                cells += [fmt(r[f"{kind}_{p}"], nd[p]) for p in PNAMES]
                lines.append(" & ".join(cells) + " \\\\")
                first_m = first_s = False
            if src == "oracle":
                lines.append("\\cmidrule(lr){2-9}")
        if mi != nm - 1:
            lines.append("\\midrule")
    lines += ["\\bottomrule", "\\end{tabular}", "\\end{table}", ""]
    return "\n".join(lines)


def main_stage2():
    rows, agg = load_stage2()
    out_csv = os.path.join(RES, "table_stage2_baselines.csv")
    agg.to_csv(out_csv, index=False, encoding="utf-8-sig")
    for kind, suffix in (("r", ""), ("b", "_bias")):
        with open(os.path.join(RES, f"table_stage2_baselines{suffix}.tex"),
                  "w", encoding="utf-8") as fh:
            fh.write(stage2_tex(agg, kind))
    pd.set_option("display.width", 260)
    show = agg.copy()
    for p in PNAMES:
        show[f"b_{p}"] = show[f"b_{p}"].map(lambda v: round(v, 3))
        show[f"r_{p}"] = show[f"r_{p}"].map(lambda v: round(v, 3))
    print(show.to_string(index=False))
    print(f"\n[TAB] saved {out_csv} (+ RMSE/bias .tex)", flush=True)
    return 0


def load_stage1():
    frames = []
    for key, label, csvname, files in STAGE1_SOURCES:
        for f in files:
            df = pd.read_csv(os.path.join(RES, f))
            if "method" in df.columns:          # baselines_stage1.csv 已含 method 列
                df = df[df["method"] == (csvname or key)].copy()
            df["method"] = key
            df["label"] = label
            df["source"] = f
            frames.append(df[["method", "label", "seed", "dgp", "T",
                              "tpr", "fdr", "f1", "wass", "medse", "source"]])
    rows = pd.concat(frames, ignore_index=True)
    agg = (rows.groupby(["method", "label", "T", "dgp"])
               .agg(S=("seed", "count"),
                    **{f"{m}_mean": (m, "mean") for m in METS},
                    **{f"{m}_std": (m, "std") for m in METS})
               .reset_index())
    src = (rows.groupby(["method", "T"])
               .agg(source=("source", lambda s: "+".join(sorted(set(s)))))
               .reset_index())
    agg = agg.merge(src, on=["method", "T"], how="left")
    order = {k: i for i, (k, _, _, _) in enumerate(STAGE1_SOURCES)}
    agg["ord"] = agg["method"].map(order)
    agg = agg.sort_values(["T", "ord", "dgp"]).drop(columns="ord").reset_index(drop=True)
    for key, _, _, _ in STAGE1_SOURCES:          # 完整性校验：防空块静默缺失
        for T in (10000, 25000):
            for dgp in "ABC":
                hit = agg[(agg["method"] == key) & (agg["T"] == T)
                          & (agg["dgp"] == dgp)]
                assert len(hit) == 1 and hit["S"].iloc[0] > 0, \
                    f"缺失数据块: {key} T={T} DGP={dgp}"
    return rows, agg


def fmt(x, nd):
    return f"{x:.{nd}f}" if np.isfinite(x) else "--"


def stage1_tex(agg):
    nd = {"tpr": 3, "fdr": 3, "f1": 3, "wass": 1, "medse": 3}
    lines = [
        "% Auto-generated by make_baseline_tables.py — 数字来自逐种子结果文件重新聚合",
        "\\begin{table}[htbp]", "\\centering", "\\small",
        "\\caption{Stage I 漂移结构识别：本文方法与外部基准对比（各种子均值）}",
        "\\label{tab:stage1_baselines}",
        "\\begin{tabular}{lll" + "c" * len(METS) + "}",
        "\\toprule",
        "$T$ & 方法 & DGP & TPR & FDR & F1 & Wass & MedSE \\\\",
        "\\midrule",
    ]
    for T in (10000, 25000):
        sub = agg[agg["T"] == T]
        first_T = True
        for key, label, _, _ in STAGE1_SOURCES:
            blk = sub[sub["method"] == key]
            for i, (_, r) in enumerate(blk.iterrows()):
                cells = [f"${T:,}$" if first_T else "",
                         label if i == 0 else "", r["dgp"]]
                cells += [fmt(r[f"{m}_mean"], nd[m]) for m in METS]
                lines.append(" & ".join(cells) + " \\\\")
                first_T = False
            if key != STAGE1_SOURCES[-1][0]:
                lines.append("\\cmidrule(lr){2-8}")
        if T != 25000:
            lines.append("\\midrule")
    lines += ["\\bottomrule", "\\end{tabular}", "\\end{table}", ""]
    return "\n".join(lines)


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--part", default="stage1", choices=["stage1", "stage2"])
    args = ap.parse_args()
    if args.part == "stage2":
        return main_stage2()
    rows, agg = load_stage1()
    out_csv = os.path.join(RES, "table_stage1_baselines.csv")
    agg.to_csv(out_csv, index=False, encoding="utf-8-sig")
    with open(os.path.join(RES, "table_stage1_baselines.tex"), "w",
              encoding="utf-8") as fh:
        fh.write(stage1_tex(agg))
    pd.set_option("display.width", 200)
    show = agg[["T", "label", "dgp", "S"] +
               [f"{m}_mean" for m in METS]].copy()
    show.columns = ["T", "方法", "DGP", "S", "TPR", "FDR", "F1", "Wass", "MedSE"]
    for m, nd in (("TPR", 3), ("FDR", 3), ("F1", 3), ("Wass", 1), ("MedSE", 3)):
        show[m] = show[m].map(lambda v: round(v, nd))
    print(show.to_string(index=False))
    print(f"\n[TAB] saved {out_csv} (+ .tex)", flush=True)
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
